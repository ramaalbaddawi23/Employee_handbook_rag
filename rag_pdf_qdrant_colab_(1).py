import torch
from transformers import AutoTokenizer, AutoModelForCausalLM

MODEL_NAME = "Qwen/Qwen2.5-0.5B-Instruct"

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
model = AutoModelForCausalLM.from_pretrained(
    MODEL_NAME,
    torch_dtype="auto",
    device_map="auto"
)

def build_prompt(question, results):
    context_str = ""
    for r in results:
        context_str += f"[Page: {r['page']}] {r['text']}\n\n"

    prompt = f"""Answer the question using only the context below.
Include the page number supporting your answer.
If the context does not contain the answer, say:
"عذراً، المعلومات التي تبحث عنها ليست مدعومة في الداتا المطروحة حالياً."

Context:
{context_str}

Question:
{question}
"""
    return prompt

def generate_rag_answer(question, top_k=3):
    results = semantic_search(question, top_k=top_k)
    prompt = build_prompt(question, results)

    messages = [
        {
            "role": "system",
            "content": "You are an employee handbook assistant. Answer strictly based on the provided context."
        },
        {
            "role": "user",
            "content": prompt
        }
    ]

    chat_text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(chat_text, return_tensors="pt").to(model.device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=200,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id
        )

    new_tokens = outputs[0][inputs["input_ids"].shape[1]:]
    answer = tokenizer.decode(new_tokens, skip_special_tokens=True)
    return answer, results

